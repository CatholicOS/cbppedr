"""Build data/curated/forms.json: the Latin forms under which each person and place of the
catalogs may appear in the Nova Vulgata text, so a reader can find them there.

For each entry: its Latin name (declined by rule), and every NVBSE label of a unit where the
edition names it differently as a name (a designation is audited for one verse only, so it is
not a global form). Every declinable word of a name is declined in the same case slot, and so is
the head of a multiword place name (mons, vallis, mare, desertum: mons Hor, montem Hor). Names ending
in a consonant, -am, -el, -on, -ath or -is, and stems under three letters, are indeclinable here, but
for the irregular ones listed (Iesus; Simon, declined in the text as Simonis, Simonem).
Generated forms that are stoplist words (stoplist_la.txt) are dropped; one that equals another
entry's name is kept (a shared form the matcher resolves). A person's multiword name also yields
the forms of its first and last words (a stoplist word gives none); these partial forms are also
listed under `partial`, so the matcher settles them only in the entry's attested units. Forms
already in the file are hand-corrected and kept as they are.

Usage: python forms.py   (reads data/persons.json and data/places.json; writes data/curated/forms.json)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FORMS = ROOT / "data/curated/forms.json"
COMMENT = ("Latin forms under which each person and place may appear in the Nova Vulgata text, "
           "generated by scripts/forms.py from the catalogs' Latin names and NVBSE labels; "
           "an entry corrected by hand is kept on regeneration. `partial` lists, of an entry's forms, those "
           "taken from a single word of a multiword name: the matcher settles them only where the entry is attested.")
STOPLIST = Path(__file__).resolve().parent / "stoplist_la.txt"
# Slots: genitive, dative, accusative, ablative, vocative (the nominative is the name). Each rule is
# (ending of the word, endings that replace it, in slot order), tried in order.
RULES = (("us", ("i", "o", "um", "o", "e")), ("es", ("is", "i", "em", "e", "es")),
         ("as", ("ae", "ae", "am", "a", "a")), ("a", ("ae", "ae", "am", "a", "a")))
# -es names are Greek or third declension: the slots are the third's, a single word adds the Greek
# genitive and accusative after them
GREEK_EXTRAS = {"es": ("i", "en")}
IRREGULAR = {"Iesus": ("Iesu", "Iesu", "Iesum", "Iesu", "Iesu"),
             "Simon": ("Simonis", "Simoni", "Simonem", "Simone", "Simon")}
# the common nouns that head a multiword place name ("mons Hor"), irregular or third declension
PLACE_HEADS = {"mons": ("montis", "monti", "montem", "monte", "mons"),
               "vallis": ("vallis", "valli", "vallem", "valle", "vallis"),
               "mare": ("maris", "mari", "mare", "mari", "mare"),
               "desertum": ("deserti", "deserto", "desertum", "deserto", "desertum")}
MIN_STEM = 3
LIGATURES = (("ae", "æ"), ("Ae", "Æ"), ("oe", "œ"), ("Oe", "Œ"))


def load_stoplist(path: Path = STOPLIST) -> frozenset[str]:
    words = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip().lower()
        if line:
            words.add(line)
    return frozenset(words)


def _slots(word: str) -> tuple[str, ...]:
    """The word's five non-nominative forms in slot order; the word itself, five times, if indeclinable."""
    if word in IRREGULAR:
        return IRREGULAR[word]
    for ending, replacements in RULES:
        if word.endswith(ending) and len(word) - len(ending) >= MIN_STEM:
            stem = word[: -len(ending)]
            return tuple(stem + r for r in replacements)
    return (word,) * 5


NEUTER_HEADS = ("mare", "desertum")
NEUTER_ADJECTIVE = ("i", "o", "um", "o", "um")  # -um after a neuter head: Rubrum, Rubri, Rubro


def _head_slots(word: str) -> tuple[str, ...] | None:
    """A place head's five forms, capitalised as the word is, or None if the word is not a head."""
    slots = PLACE_HEADS.get(word.lower())
    if slots is None:
        return None
    return tuple(s[:1].upper() + s[1:] for s in slots) if word[:1].isupper() else slots


def _other_spelling(form: str) -> str | None:
    if any(a in form for a, _ in LIGATURES):
        for a, lig in LIGATURES:
            form = form.replace(a, lig)
        return form
    if any(lig in form for _, lig in LIGATURES):
        for a, lig in LIGATURES:
            form = form.replace(lig, a)
        return form
    return None


def _extras(word: str) -> list[str]:
    for ending, replacements in GREEK_EXTRAS.items():
        if word.endswith(ending) and len(word) - len(ending) >= MIN_STEM and word not in IRREGULAR:
            return [word[: -len(ending)] + r for r in replacements]
    return []


def propose_parts(name: str, stoplist: frozenset[str] | None = None, person: bool = False,
                  places: frozenset[str] = frozenset(), place: bool = False) -> tuple[list[str], list[str]]:
    """The name's own forms: the name first, then its case forms (every declinable word in the same
    slot), no duplicates; and its partial forms: for a multiword name, the forms of its first word
    (unless that is a stoplist word) and, for a person, of its last word (unless that is a stoplist
    word or the name of a place in `places`), less any of the name's own forms.
    A generated form in the stoplist is dropped; a form with ae/oe or its ligature is followed by the
    other spelling. In a multiword `place` name, a head mons, vallis, mare or desertum is declined too."""
    name = name.strip()
    if not name:
        return [], []
    stop = load_stoplist() if stoplist is None else stoplist
    words = name.split()
    slots = [_slots(w) for w in words]
    head = _head_slots(words[0]) if place and len(words) > 1 else None
    if head:
        slots[0] = head
        if words[0].lower() in NEUTER_HEADS:  # its adjectives agree with it: mari Rubro, not mari Rubrum
            for i, w in enumerate(words[1:], 1):
                if w.endswith("um") and len(w) - 2 >= MIN_STEM:
                    slots[i] = tuple(w[:-2] + e for e in NEUTER_ADJECTIVE)
    generated = [" ".join(s[i] for s in slots) for i in range(5)]
    if head and words[0][:1].isupper():  # the text writes the head lower-case: mare Rubrum, montem Hor
        generated += [f[:1].lower() + f[1:] for f in [name] + generated]
    if len(words) == 1:
        generated += _extras(words[0])
    forms = [name] + [f for f in generated if f.lower() not in stop]
    full: list[str] = []
    for f in dict.fromkeys(forms):
        full.append(f)
        alt = _other_spelling(f)
        if alt:
            full.append(alt)
    full = list(dict.fromkeys(full))
    return full, [f for f in _word_forms(words, stop, person, places, head) if f not in full]


def _word_forms(words: list[str], stop: frozenset[str], person: bool, places: frozenset[str],
                head: tuple[str, ...] | None = None) -> list[str]:
    """A multiword name's first word's forms (a place head's own slots: Mons, Montem) and, for a person,
    its last word's; none from a stoplist word."""
    if len(words) < 2:
        return []
    out: list[str] = []
    if words[0].lower() not in stop:
        out += [words[0]] + [f for f in head if f.lower() not in stop] if head else propose(words[0], stop)
    last = words[-1]
    if person and last.lower() not in stop and last not in places:
        out += propose(last, stop)
    return list(dict.fromkeys(out))


def propose(name: str, stoplist: frozenset[str] | None = None, person: bool = False,
            places: frozenset[str] = frozenset(), place: bool = False) -> list[str]:
    """All the forms of `propose_parts`: the name's own, then its partial ones."""
    full, partial = propose_parts(name, stoplist, person, places, place)
    return full + partial


def _entry_forms(id_: str, entry: dict, stop: frozenset[str],
                 places: frozenset[str]) -> tuple[list[str], list[str]]:
    """The entry's forms (its Latin name, then its NVBSE name labels) and, of them, the partial ones:
    those that only a single word of a multiword name gives."""
    person = id_.startswith("bpers:")
    names = [entry.get("names", {}).get("la") or ""]
    for label in entry.get("labels", {}).values():
        text = label.get("editions", {}).get("NVBSE")
        if text and label.get("as") == "name":
            names.append(text)
    forms: list[str] = []
    full: set[str] = set()
    partial: list[str] = []
    for name in names:
        own, part = propose_parts(name, stop, person, places, id_.startswith("bplace:"))
        forms += own + part
        full.update(own)
        partial += part
    return list(dict.fromkeys(forms)), [f for f in dict.fromkeys(partial) if f not in full]


def build_all(catalogs: dict[str, dict], existing: dict[str, list[str]],
              existing_partial: dict[str, list[str]]) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """By id, the forms and (only where any) the partial forms; an id in `existing` is kept as it is."""
    stop = load_stoplist()
    places = frozenset((e.get("names", {}).get("la") or "").strip()
                       for e in catalogs.get("places", {}).get("entries", {}).values()) - {""}
    out: dict[str, list[str]] = {}
    partial: dict[str, list[str]] = {}
    for catalog in catalogs.values():
        for id_, entry in catalog["entries"].items():
            if id_ in existing:
                forms, part = existing[id_], existing_partial.get(id_, [])
            else:
                forms, part = _entry_forms(id_, entry, stop, places)
            if forms:
                out[id_] = forms
            if forms and part:
                partial[id_] = part
    # hand-corrected ids no longer in a catalog are dropped on purpose: nothing to find
    return dict(sorted(out.items())), dict(sorted(partial.items()))


def build(catalogs: dict[str, dict], existing: dict[str, list[str]]) -> dict[str, list[str]]:
    return build_all(catalogs, existing, {})[0]


def main() -> int:
    catalogs = {t: json.loads((ROOT / f"data/{t}.json").read_text(encoding="utf-8")) for t in ("persons", "places")}
    doc = json.loads(FORMS.read_text(encoding="utf-8")) if FORMS.exists() else {}
    forms, partial = build_all(catalogs, doc.get("forms", {}), doc.get("partial", {}))
    FORMS.write_text(json.dumps({"$comment": COMMENT, "forms": forms, "partial": partial},
                                ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(forms)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
