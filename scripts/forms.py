"""Build data/curated/forms.json: the Latin forms under which each person and place of the
catalogs may appear in the Nova Vulgata text, so a reader can find them there.

For each entry: its Latin name (declined by rule), and every NVBSE label of a unit where the
edition names it differently (a name is declined, a designation is kept verbatim). Only the
first word of a multiword name is declined. Hebrew names ending in a consonant, -am, -el, -on,
-ath and names in -is are indeclinable here. Forms already in the file are hand-corrected and
kept as they are.

Usage: python forms.py   (reads data/persons.json and data/places.json; writes data/curated/forms.json)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FORMS = ROOT / "data/curated/forms.json"
COMMENT = ("Latin forms under which each person and place may appear in the Nova Vulgata text, "
           "generated by scripts/forms.py from the catalogs' Latin names and NVBSE labels; "
           "an entry corrected by hand is kept on regeneration.")
# (ending of the head word, endings that replace it), tried in order
RULES = (("us", ("i", "o", "um", "e")), ("es", ("i", "en", "e")), ("as", ("ae", "am")), ("a", ("ae", "am")))


def _decline(word: str) -> list[str]:
    for ending, replacements in RULES:
        if word.endswith(ending) and len(word) > len(ending):
            stem = word[: -len(ending)]
            return [stem + r for r in replacements]
    return []


def propose(name: str) -> list[str]:
    """The name first, then the case forms of its head word (the rest kept), no duplicates."""
    name = name.strip()
    if not name:
        return []
    head, _, rest = name.partition(" ")
    forms = [name] + [f + (" " + rest if rest else "") for f in _decline(head)]
    return list(dict.fromkeys(forms))


def _entry_forms(entry: dict) -> list[str]:
    forms = propose(entry.get("names", {}).get("la") or "")
    for label in entry.get("labels", {}).values():
        text = label.get("editions", {}).get("NVBSE")
        if not text:
            continue
        forms += propose(text) if label.get("as") == "name" else [text.strip()]
    return list(dict.fromkeys(f for f in forms if f))


def build(catalogs: dict[str, dict], existing: dict[str, list[str]]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for catalog in catalogs.values():
        for id_, entry in catalog["entries"].items():
            if id_ in existing:
                out[id_] = existing[id_]
                continue
            forms = _entry_forms(entry)
            if forms:
                out[id_] = forms
    # hand-corrected ids no longer in a catalog are dropped on purpose: nothing to find
    return dict(sorted(out.items()))


def main() -> int:
    catalogs = {t: json.loads((ROOT / f"data/{t}.json").read_text(encoding="utf-8")) for t in ("persons", "places")}
    existing = json.loads(FORMS.read_text(encoding="utf-8"))["forms"] if FORMS.exists() else {}
    forms = build(catalogs, existing)
    FORMS.write_text(json.dumps({"$comment": COMMENT, "forms": forms}, ensure_ascii=False, indent=1) + "\n",
                     encoding="utf-8")
    print(f"{len(forms)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
