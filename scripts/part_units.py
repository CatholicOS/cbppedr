"""Turn the reviewers' reference numbers per entity into units: data/curated/part-units.json.

Usage: python part_units.py
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PRIVATE = Path(os.environ.get("CBPPEDR_PRIVATE", Path.home() / "development/BibleGet-I-O/data-local/cbppedr"))


def convert(reviews: list[dict], refs_units: dict[str, list[list[str]]]) -> tuple[dict, list[str]]:
    out: dict[str, dict[str, list[str]]] = {}
    problems: list[str] = []
    for r in reviews:
        refs = refs_units.get(r["key"])
        if refs is None:
            problems.append(f"{r['key']}: no such multi-entity sense")
            continue
        per: dict[str, list[str]] = {}
        for eid, idx in r.get("assign", {}).items():
            units: list[str] = []
            for i in idx:
                if not 0 <= i < len(refs):
                    problems.append(f"{r['key']}: reference {i} out of range")
                    continue
                units += [u for u in refs[i] if u not in units]
            per[eid] = units
        out[r["key"]] = per
    return out, problems


def main() -> int:
    refs_units = json.loads((PRIVATE / "part-refs-units.json").read_text(encoding="utf-8"))
    reviews = []
    for f in sorted((PRIVATE / "review").glob("parts-*.jsonl")):
        reviews += [json.loads(l) for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]
    out, problems = convert(reviews, refs_units)
    for p in problems:
        print(p)
    doc = {"$comment": "The units each entity of a multi-entity dictionary sense is attested in, as assigned by "
                       "review (key -> entity id -> units). Generated by scripts/part_units.py.",
           "parts": dict(sorted(out.items()))}
    (ROOT / "data/curated/part-units.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(out)} senses, {len(problems)} problems")
    return 0


if __name__ == "__main__":
    sys.exit(main())
