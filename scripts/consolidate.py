"""Collect the reviewers' sense decisions into data/curated/senses.json, facts only.

Each review file has one line per sense of its batch, in batch order; a decision is
matched to its sense by position (batch keys could repeat before senses got unique
keys), and given the sense's current key. Reviewers' free-text notes stay private.

Usage: python consolidate.py
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PRIVATE = Path(os.environ.get("CBPPEDR_PRIVATE", Path.home() / "development/BibleGet-I-O/data-local/cbppedr"))
FIELDS = ("type", "kind", "id", "latin", "it", "en", "descr_it", "descr_en", "relations", "parts", "certain")


def _facts(d: dict) -> dict:
    out = {k: d[k] for k in FIELDS if k in d and d[k] is not None}
    if out.get("parts"):
        out["parts"] = [_facts(p) for p in out["parts"]]
    return out


def consolidate(batches: list[tuple[list[dict], list[dict]]], senses: list[dict]) -> list[dict]:
    out: list[dict] = []
    pos = 0
    for batch, review in batches:
        if len(batch) != len(review):
            raise ValueError(f"review has {len(review)} lines for {len(batch)} senses")
        for b, r in zip(batch, review):
            sense = senses[pos]
            if sense["key"].split("~")[0] != b["key"].split("~")[0] or r.get("key", b["key"]) != b["key"]:
                raise ValueError(f"position {pos}: {b['key']} / {r.get('key')} / {sense['key']}")
            out.append({"key": sense["key"], **_facts(r)})
            pos += 1
    if pos != len(senses):
        raise ValueError(f"{pos} decisions for {len(senses)} senses")
    return out


def _jsonl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]


def main() -> int:
    batches = []
    n = 1
    while (PRIVATE / f"batches/senses-{n}.jsonl").exists():
        batches.append((_jsonl(PRIVATE / f"batches/senses-{n}.jsonl"), _jsonl(PRIVATE / f"review/classify-{n}.jsonl")))
        n += 1
    decisions = consolidate(batches, _jsonl(PRIVATE / "ndeib-senses.jsonl"))
    doc = {"$comment": "Reviewed decision for each sense of the dictionary (key: headword#sense): its type, "
                       "identifier, names, our own short descriptions and relations. Facts only. "
                       "Generated by scripts/consolidate.py from the review files.",
           "decisions": decisions}
    (ROOT / "data/curated/senses.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(decisions)} decisions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
