"""Find persons and places the catalog misses, using STEPBible's TIPNR list as a pointer.

TIPNR (CC BY 4.0, Tyndale House) is read from the private folder; nothing of it is
written to data/. The report lists, by book, the TIPNR individuals none of whose
verses is attested by a catalog entry of the same type: round-2 work. TIPNR's
references (English versification) are resolved through CBTUDR's NABRE map, so a
few psalm and chapter-boundary verses may be off by one.

Usage: python stepbible_check.py   (writes docs/stepbible-gaps.md)
"""

from __future__ import annotations

import json
import os
import re
import sys
from functools import cache
from pathlib import Path

from units import CBTUDR

ROOT = Path(__file__).resolve().parent.parent
TIPNR = Path(os.environ.get("TIPNR", Path.home() / "development/BibleGet-I-O/data-local/stepbible/tipnr.txt"))
STEP_BOOKS = ("Gen Exo Lev Num Deu Jos Jdg Rut 1Sa 2Sa 1Ki 2Ki 1Ch 2Ch Ezr Neh - - Est - - Job Psa Pro Ecc Sng "
              "- - Isa Jer Lam - Ezk Dan Hos Jol Amo Oba Jon Mic Nam Hab Zep Hag Zec Mal Mat Mrk Luk Jhn Act "
              "Rom 1Co 2Co Gal Eph Php Col 1Th 2Th 1Ti 2Ti Tit Phm Heb Jas 1Pe 2Pe 1Jn 2Jn 3Jn Jud Rev").split()
BOOK_NO = {b: i for i, b in enumerate(STEP_BOOKS, 1) if b != "-"}  # BibleGet/CBTUDR numbering


@cache
def _nabre(book: int) -> dict[str, list[str]]:
    paths = list((CBTUDR / "data/maps/nabre").glob(f"{book:02d}-*.json"))
    if not paths:
        return {}
    return {v["ref"].split("@")[0]: v["units"] for v in json.loads(paths[0].read_text(encoding="utf-8"))["verses"]}


def _units(refs: str) -> list[str]:
    out: list[str] = []
    for r in re.findall(r"([1-3]?[A-Z][a-z]{1,2})\.(\d+)\.(\d+)", refs):
        book = BOOK_NO.get(r[0])
        if book:
            for u in _nabre(book).get(f"{r[1]}:{r[2]}", []):
                if u not in out:
                    out.append(u)
    return out


def read_tipnr(path: Path) -> list[dict]:
    recs: list[dict] = []
    section = None
    cur = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("$=========="):
            head = line.strip("$= \t")
            section = "person" if head.startswith("PERSON") else "place" if head.startswith("PLACE") else None
            cur = None
            continue
        if section is None or not line.strip():
            continue
        f = line.split("\t")
        if cur is None and "@" in f[0] and not f[0].startswith("–"):
            cur = {"name": f[0].split("=")[0], "type": section, "units": []}
            recs.append(cur)
        elif cur is not None and f[0].startswith("– ") and not f[0].startswith("– Total") and len(f) > 4:
            for u in _units(f[4]):
                if u not in cur["units"]:
                    cur["units"].append(u)
    return recs


def _close(a: str, b: str) -> bool:
    a, b = a.lower(), b.lower()
    if a == b:
        return True
    if abs(len(a) - len(b)) > 1:
        return False
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1] <= 1


def gaps(recs: list[dict], entries: list[dict]) -> list[dict]:
    """TIPNR individuals no entry covers: same type, a close English name, and a shared verse."""
    out = []
    for r in recs:
        name = r["name"].split("@")[0]
        units = set(r["units"])
        if units and not any(e["type"] == r["type"] and units & e["attested"] and _close(name, e["en"] or "")
                             for e in entries):
            out.append(r)
    return out


def main() -> int:
    entries = []
    for name in ("persons", "places"):
        for e in json.loads((ROOT / "data" / f"{name}.json").read_text(encoding="utf-8"))["entries"].values():
            for en in {e["names"].get("en"), e["names"].get("la"), e["names"].get("it")} - {None}:
                entries.append({"type": e["type"], "en": en, "attested": set(e["attested"])})
    recs = read_tipnr(TIPNR)
    missing = gaps(recs, entries)
    lines = ["# Persons and places the catalog does not yet cover", "",
             "Generated by `scripts/stepbible_check.py`; do not edit. Each line is a TIPNR individual "
             "(STEPBible.org, CC BY 4.0) none of whose verses an entry of the same type attests: work for round 2. "
             "TIPNR serves only as a pointer; no data of it is in this repository.", "",
             f"{len(missing)} of {len(recs)} TIPNR persons and places.", ""]
    for t in ("person", "place"):
        rows = [r for r in missing if r["type"] == t]
        lines += [f"## {t.capitalize()}s ({len(rows)})", ""]
        lines += [f"- `{r['name']}` ({len(r['units'])} verses, first {r['units'][0]})" for r in rows]
        lines.append("")
    (ROOT / "docs/stepbible-gaps.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(missing)} gaps of {len(recs)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
