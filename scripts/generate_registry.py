"""Write registry/{persons,places,events}.md: one table per catalog, by initial letter.

Usage: python generate_registry.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def table(title: str, cat: dict) -> str:
    lines = [f"# {title}", "", "Generated by `scripts/generate_registry.py` from `data/`; do not edit. "
             "Identifiers are drafts pending committee review.", ""]
    letter = None
    for eid, e in sorted(cat["entries"].items(), key=lambda kv: kv[0].split(":", 1)[1]):
        first = eid.split(":", 1)[1][0].upper()
        if first != letter:
            letter = first
            lines += ["", f"## {letter}", "", "| Identifier | Italian | English | Description | Kind | Verses | Wikidata |",
                      "|---|---|---|---|---|---|---|"]
        q = f"[{e['qid']}](https://www.wikidata.org/wiki/{e['qid']})" if e.get("qid") else ""
        lines.append(f"| `{eid}` | {e['names'].get('it') or ''} | {e['names'].get('en') or ''} | "
                     f"{(e.get('description') or {}).get('en') or ''} | {e.get('kind') or ''} | "
                     f"{len(e['attested'])} | {q} |".replace("|  |", "| |"))
    return "\n".join(lines) + "\n"


def main() -> int:
    for name in ("persons", "places", "events"):
        cat = json.loads((ROOT / "data" / f"{name}.json").read_text(encoding="utf-8"))
        (ROOT / "registry" / f"{name}.md").write_text(table(name.capitalize(), cat), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
