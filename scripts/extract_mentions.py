ROOT = Path(__file__).resolve().parent.parent
EDITION = "NVBSE"
OUT = ROOT / "data/mentions/nvbse.json"
REMOVED = ROOT / "data/curated/unattested.json"
LOCAL = Path(os.environ.get("MENTIONS_LOCAL",
                            Path.home() / "development/BibleGet-I-O/data-local/cbppedr/mentions"))
REPORT = LOCAL / "nvbse-report.json"
COMMENT = ("Where each person and place of the catalogs is named in the Nova Vulgata (NVBSE), by CBTUDR unit: "
           "start/end in UTF-16 code units of the verse's text_plain, check = first 8 hex digits of SHA-256 of "
           "the span, hash = SHA-256 of text_plain; entry when settled, candidates when under review. "
           "Generated by scripts/extract_mentions.py.")

Hit = tuple[int, int, str]
FOLDS = (("æ", "ae"), ("œ", "oe"))
MIN_BOOK_UNITS = 3  # a shared form settles by book to a bearer cited this often there, or in the chapter


def utf16(s: str, i: int) -> int:
    """The UTF-16 code-unit offset of code point `i` in `s`."""
    return i + sum(1 for c in s[:i] if ord(c) > 0xFFFF)


def check(span: str) -> str:
    return hashlib.sha256(span.encode("utf-8")).hexdigest()[:8]


def _is_letter(c: str) -> bool:
    return c.isalpha() or unicodedata.category(c).startswith("M")


def _index(forms: dict[str, list[str]]) -> dict[str, list[tuple[str, list[str]]]]:
    """By first word, the forms starting with it, longest first, each with its sorted entries."""
    by_form: dict[str, set[str]] = {}
    for id_, fs in forms.items():
        for f in fs:
            if f and _is_letter(f[0]):
                by_form.setdefault(f, set()).add(id_)
    index: dict[str, list[tuple[str, list[str]]]] = {}
    for f, ids in by_form.items():
        index.setdefault(_word_at(f, 0), []).append((f, sorted(ids)))
    for entries in index.values():
        entries.sort(key=lambda e: -len(e[0]))
    return index


def _match_at(text: str, i: int, index: dict) -> tuple[str, list[str]] | None:
    for form, ids in index.get(_word_at(text, i), ()):
        end = i + len(form)
        if text.startswith(form, i) and (end == len(text) or not _is_letter(text[end])):
            return form, ids
    return None


def _word_at(text: str, i: int) -> str:
    end = i
    while end < len(text) and _is_letter(text[end]):
        end += 1
    return text[i:end]


def _find_indexed(text: str, index: dict) -> list[Hit]:
    hits: list[Hit] = []
    for i, c in enumerate(text):
        if not _is_letter(c) or (i > 0 and _is_letter(text[i - 1])):
            continue
        match = _match_at(text, i, index)
        if match:
            hits += [(i, i + len(match[0]), id_) for id_ in match[1]]
    return hits


def _is_name_form(form: str) -> bool:
    """A name starts with a capital; a lower-case form is kept only as a whole label of several words
    ("trans Iordanem"), not as a lone common noun ("via", "domum") taken from one."""
    return not form[:1].islower() or " " in form.strip()


def name_forms(forms: dict[str, list[str]]) -> dict[str, list[str]]:
    return {id_: [f for f in fs if _is_name_form(f)] for id_, fs in forms.items()}


def find(text: str, forms: dict[str, list[str]]) -> list[Hit]:
    """Every whole-word occurrence of a name form: (start, end) in code points, one hit per entry of the form."""
    return _find_indexed(text, _index(name_forms(forms)))


def _longest(hits: list[Hit]) -> list[Hit]:
    """At each start, only the longest span's hits, whichever source they came from (names, lower-case
    canonical forms, designations): a designation "rex" inside a name "rex Aegypti" is not kept."""
    end = {}
    for s, e, _ in hits:
        end[s] = max(end.get(s, e), e)
    return [h for h in hits if h[1] == end[h[0]]]


def _spans(hits: list[Hit]) -> dict[tuple[int, int], set[str]]:
    spans: dict[tuple[int, int], set[str]] = {}
    for start, end, id_ in hits:
        spans.setdefault((start, end), set()).add(id_)
    return spans


def _crossing(spans: list[tuple[int, int]]) -> set[tuple[int, int]]:
    out = set()
    for a in spans:
        for b in spans:
            if a[0] < b[0] < a[1] < b[1]:
                out |= {a, b}
    return out


def stem(word: str) -> str:
    """The first 4 letters of a word, lower-cased, ligatures spelled out and doubled letters single."""
    word = word.lower()
    for lig, plain in FOLDS:
        word = word.replace(lig, plain)
    return re.sub(r"(.)\1+", r"\1", word)[:4]


Outside = Callable[[str, str], bool]
Rivals = Callable[[str, str], list[str]]


def _never(words: str, id_: str) -> bool:
    return False


def _none(words: str, id_: str) -> list[str]:
    return []


def _decide(words: str, ids: set[str], attested_here: set[str], designated_ids: set[str],
            outside: Outside, rivals: Rivals = _none, in_book: Callable[[str], bool] = lambda id_: False,
            firm: Callable[[str], bool] = lambda id_: True) -> tuple[str, list[str]]:
    if len(designated_ids) == 1:
        return "entry", sorted(designated_ids)
    here = ids & attested_here
    if len(here) == 1:
        return "entry", sorted(here)
    # outside the attested units: the one entry of the form, or the one of its bearers attested in the book
    bearer = next(iter(ids)) if len(ids) == 1 else None
    if bearer is None and not here:
        in_this_book = [id_ for id_ in ids if in_book(id_)]
        bearer = in_this_book[0] if len(in_this_book) == 1 and firm(in_this_book[0]) else None
    if not here and bearer is not None:
        also = rivals(words, bearer)
        if also:
            return "candidates", sorted(ids | set(also))
        if outside(words, bearer):
            return "outside", [bearer]
    return "candidates", sorted(ids)


def _nested_conflicts(decided: dict[tuple[int, int], tuple[str, list[str]]],
                      attested_here: set[str]) -> None:
    """An outside settle (`outside`) whose span holds a nested span settled to another entry attested in
    the unit is not settled: the outer form may mean that entry too ("desertum Sin" around the attested
    wilderness of Zin's "Sin"), so it becomes candidates of both. Every other outside settle is settled."""
    for (start, end), (key, value) in decided.items():
        if key != "outside":
            continue
        others = {v[0] for (s, e), (k, v) in decided.items()
                  if k == "entry" and start <= s and e <= end and (s, e) != (start, end)
                  and v[0] in attested_here and v[0] not in value}
        decided[(start, end)] = ("candidates", sorted(set(value) | others)) if others else ("entry", value)


def resolve(text: str, hits: list[Hit], attested_here: set[str], designated: frozenset[Hit] | set[Hit] = frozenset(),
            outside: Outside = _never, repeated: frozenset[Hit] | set[Hit] = frozenset(),
            rivals: Rivals = _none, in_book: Callable[[str], bool] = lambda id_: False,
            firm: Callable[[str], bool] = lambda id_: True) -> list[dict]:
    """The hits of one verse as mentions (UTF-16 positions), crossing spans left out. `designated` are
    the hits that came from the entry's designation label for this unit, `repeated` those of them whose
    label is found more than once there (each a candidate, never settled); `outside(words, id)` says
    whether a form of one entry not attested in the unit may settle it anyway, unless `rivals(words, id)`
    names other entries it may mean (then they are candidates with it)."""
    spans = _spans(hits)
    crossing = _crossing(list(spans))
    decided: dict[tuple[int, int], tuple[str, list[str]]] = {}
    for (start, end), ids in sorted(spans.items()):
        if (start, end) in crossing:
            continue
        words = text[start:end]
        mine = {id_ for id_ in ids if (start, end, id_) in designated}
        if any((start, end, id_) in repeated for id_ in ids):
            decided[(start, end)] = ("candidates", sorted(ids))
        else:
            decided[(start, end)] = _decide(words, ids, attested_here, mine, outside, rivals, in_book, firm)
    _nested_conflicts(decided, attested_here)
    out = []
    for (start, end), (key, value) in sorted(decided.items()):
        words = text[start:end]
        mention = {"start": utf16(text, start), "end": utf16(text, end), "check": check(words)}
        mention[key] = value[0] if key == "entry" else value
        out.append(mention)
    return out


def base_unit(key: str) -> str:
    return key.split("@", 1)[0]


def book(unit: str) -> str:
    """The book code of a unit key: `btu:1par.24.2@GREEK` is `1par`."""
    return base_unit(unit).removeprefix("btu:").split(".", 1)[0]


def chapter(unit: str) -> str:
    """The book and chapter of a unit key: `btu:1par.24.2@GREEK` is `1par.24`."""
    return ".".join(base_unit(unit).removeprefix("btu:").split(".")[:2])


def _entries(catalogs: dict[str, dict]):
    for name in ("persons", "places"):
        yield from catalogs.get(name, {}).get("entries", {}).items()


def _attestations(catalogs: dict[str, dict]) -> tuple[dict[str, set[str]], dict[str, dict[str, list[str]]]]:
    """By unit: the entries attested there, and the entries' NVBSE designation labels there."""
    attested: dict[str, set[str]] = {}
    designations: dict[str, dict[str, list[str]]] = {}
    for id_, entry in _entries(catalogs):
        for unit in entry.get("attested", []):
            attested.setdefault(base_unit(unit), set()).add(id_)
        for unit, label in entry.get("labels", {}).items():
            text = label.get("editions", {}).get(EDITION)
            if text and label.get("as") == "designation":
                designations.setdefault(base_unit(unit), {}).setdefault(id_, []).append(text)
    return attested, designations


def _review_rows(key: str, text: str, mentions: list[dict]) -> list[dict]:
    rows = []
    for m in mentions:
        if "candidates" in m:
            rows.append({"unit": key, "start": m["start"], "end": m["end"],
                         "words": _utf16_slice(text, m["start"], m["end"]), "candidates": m["candidates"]})
    return rows


def _utf16_slice(text: str, start: int, end: int) -> str:
    return text.encode("utf-16-le")[2 * start:2 * end].decode("utf-16-le")


def _crossing_row(key: str, text: str, hits: list[Hit]) -> dict | None:
    spans = _spans(hits)
    crossing = sorted(_crossing(list(spans)))
    if not crossing:
        return None
    return {"unit": key, "spans": [{"start": utf16(text, s), "end": utf16(text, e), "words": text[s:e],
                                    "ids": sorted(spans[(s, e)])} for s, e in crossing]}


class _Run:
    """The accumulating state of one extraction."""

    def __init__(self, forms, catalogs, stop, partial, removed=None, testaments=None):
        self.index = _index(name_forms(forms))
        self.stems = {id_: {stem(w) for f in fs for w in f.split()} for id_, fs in forms.items()}
        # lower-case one-word canonical forms ("praetorium"): looked for only where the entry is attested
        part = {id_: set(fs) for id_, fs in (partial or {}).items()}
        self.lower = {id_: low for id_, fs in forms.items()
                      if (low := [f for f in fs if not _is_name_form(f) and f not in part.get(id_, ())])}
        self.attested, self.designations = _attestations(catalogs)
        self.books: dict[str, set[str]] = {}
        self.book_units: dict[tuple[str, str], int] = {}  # (entry, book) -> attested units there
        self.chapters: set[tuple[str, str]] = set()  # (entry, "book.chapter")
        for unit, ids in self.attested.items():
            for id_ in ids:
                self.books.setdefault(id_, set()).add(book(unit))
                self.book_units[(id_, book(unit))] = self.book_units.get((id_, book(unit)), 0) + 1
                self.chapters.add((id_, chapter(unit)))
        self.partial = {id_: set(fs) for id_, fs in (partial or {}).items()}
        # by book code its Testament (OT, deuterocanonical books included, or NT); None: no limit
        self.testaments = testaments
        self.entry_testaments = {id_: {testaments.get(b) for b in bs} for id_, bs in self.books.items()} \
            if testaments is not None else {}
        self.removed = {id_: {base_unit(u) for u in us} for id_, us in (removed or {}).items()}
        self.stop = {w.lower() for w in stop}
        self.units: dict[str, dict] = {}
        self.found: dict[str, set[str]] = {}
        self.review: list[dict] = []
        self.crossing: list[dict] = []

    def unit(self, key: str, row: dict) -> None:
        text, unit = row["text"], base_unit(key)
        hits = _find_indexed(text, self.index)
        lower = {id_: self.lower[id_] for id_ in self.attested.get(unit, set()) if id_ in self.lower}
        hits += [h for h in _find_indexed(text, _index(lower)) if h not in hits] if lower else []
        labels = self.designations.get(unit, {})
        designated = set(_find_indexed(text, _index(labels)))
        hits += [h for h in designated if h not in hits]
        hits = _longest(self.in_testament(hits, unit))
        designated &= set(hits)
        crossing = _crossing(list(_spans(hits)))
        here = {id_ for start, end, id_ in hits if (start, end) not in crossing}
        self.found.setdefault(unit, set()).update(here)
        unmatched = self.attested.get(unit, set()) - here
        # a label found more than once, counted on its own (before the longest span wins at a position)
        twice = {id_ for id_, ls in labels.items() if len(_find_indexed(text, _index({id_: ls}))) > 1}
        repeated = {h for h in designated if h[2] in twice}
        mentions = resolve(text, hits, self.attested.get(unit, set()), designated,
                           self.outside(book(unit), unit), repeated, self.rivals(unmatched),
                           lambda id_: book(unit) in self.books.get(id_, ()), self.firmly_in_book(unit))
        row_crossing = _crossing_row(key, text, hits)
        if row_crossing:
            self.crossing.append(row_crossing)
        if mentions:
            self.units[key] = {"hash": row["hash"], "mentions": mentions}
            self.review += _review_rows(key, text, mentions)

    def in_testament(self, hits: list[Hit], unit: str) -> list[Hit]:
        """In an Old Testament unit, the hits but those of a person attested only outside the Old
        Testament: a name whose only bearers are New Testament persons ("Maria", the seas named in Gn 1:10)
        is not a candidate there. A New Testament unit keeps every hit (it names Old Testament persons too:
        Isaias, Melchisedech), and so does a place (Antioch and Cilicia of Maccabees are those of Acts)."""
        if self.testaments is None or self.testaments.get(book(unit)) != "OT":
            return hits
        return [h for h in hits if not h[2].startswith("bpers:") or "OT" in self.entry_testaments.get(h[2], ())]

    def outside(self, here: str, unit: str = "") -> Outside:
        """Outside its attested units, a form of one entry settles it only if the entry is attested in
        the same book, the form is not one of a single word of a multiword name, nor a stoplist word, and
        the unit is not one a review removed from the entry (unattested.json: it does not refer to it)."""
        def settles(words: str, id_: str) -> bool:
            return (here in self.books.get(id_, ()) and words not in self.partial.get(id_, ())
                    and words.lower() not in self.stop and unit not in self.removed.get(id_, ()))
        return settles

    def firmly_in_book(self, unit: str) -> Callable[[str], bool]:
        """Whether the one bearer of a shared form attested in the unit's book is attested in the unit's
        chapter, or in 3 or more units of the book: only then may the shared form settle to it by book (one citation elsewhere in the book is
        not enough: Jason the high priest of 2 Mc 4:7 is not the Jason of Cyrene cited in 2 Mc 2:23)."""
        here, chap = book(unit), chapter(unit)
        return lambda id_: (id_, chap) in self.chapters or self.book_units.get((id_, here), 0) >= MIN_BOOK_UNITS

    def rivals(self, unmatched: set[str]) -> Rivals:
        """The entries attested in the unit but not found there, one of whose forms has a word of the
        form's stem: the form may be theirs, spelled otherwise. Persons and places alike, since a people
        and its land share a stem (Gesuri where Gessur is attested)."""
        def same_stem(words: str, id_: str) -> list[str]:
            first = stem(words.split()[0])
            return sorted(u for u in unmatched if first in self.stems.get(u, ()))
        return same_stem

    def unmatched(self) -> list[dict]:
        rows = []
        for unit in sorted(self.found):
            for id_ in sorted(self.attested.get(unit, set()) - self.found[unit]):
                rows.append({"unit": unit, "entry": id_})
        return rows


def extract(texts: dict[str, dict], forms: dict[str, list[str]], catalogs: dict[str, dict],
            stop, partial: dict[str, list[str]] | None = None,
            removed: dict[str, list[str]] | None = None,
            testaments: dict[str, str] | None = None) -> tuple[dict, dict]:
    """The public file's body and the private report; `partial` lists by entry its forms taken from a
    single word of a multiword name; `removed`, by entry, the units a review says do not refer to it;
    `testaments`, by book code, its Testament (a candidate must be attested in the unit's)."""
    run = _Run(forms, catalogs, stop, partial, removed, testaments)
    for key in sorted(texts):
        run.unit(key, texts[key])
    unmatched = run.unmatched()
    mentions = [m for u in run.units.values() for m in u["mentions"]]
    under_review = sum(1 for m in mentions if "candidates" in m)
    counts = {"units": len(run.units), "mentions": len(mentions), "settled": len(mentions) - under_review,
              "under_review": under_review, "unmatched": len(unmatched),
              "crossing": sum(len(c["spans"]) for c in run.crossing)}
    body = {"$comment": COMMENT, "edition": EDITION, "units": run.units}
    report = {"edition": EDITION, "counts": counts, "unmatched": unmatched, "crossing": run.crossing,
              "under_review": run.review}
    return body, report


def merged_mentions(generated: dict, curated: dict) -> dict:
    """The generated file with the curated units laid over it: a curated unit replaces the generated
    one, and a curated unit with no mentions removes it."""
    units = dict(generated["units"])
    for key, unit in curated.get("units", {}).items():
        if unit.get("mentions"):
            units[key] = unit
        else:
            units.pop(key, None)
    return {**generated, "units": units}


def _write(path: Path, data: dict, indent: int | None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=indent) + "\n", encoding="utf-8")


def main() -> int:
    texts = json.loads((TEXTS / f"{EDITION}-plain.json").read_text(encoding="utf-8"))
    forms_doc = json.loads(FORMS.read_text(encoding="utf-8"))
    catalogs = {t: json.loads((ROOT / f"data/{t}.json").read_text(encoding="utf-8")) for t in ("persons", "places")}
    removed = json.loads(REMOVED.read_text(encoding="utf-8"))["entries"] if REMOVED.exists() else {}
    books = json.loads((CBTUDR / "data/books.json").read_text(encoding="utf-8"))["books"]
    testaments = {b["segment"]: b["testament"] for b in books}
    body, report = extract(texts, forms_doc["forms"], catalogs, load_stoplist(), forms_doc.get("partial", {}), removed,
                           testaments)
    _write(OUT, body, 1)
    _write(REPORT, report, 1)
    print(json.dumps(report["counts"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
