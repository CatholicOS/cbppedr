"""Find the persons and places of the catalogs in every verse of the Nova Vulgata (NVBSE) and write
their positions, never their words, to data/mentions/nvbse.json.

Reads the private export of NVBSE's text_plain by unit (export_texts.py --plain), the forms of
data/curated/forms.json, and the catalogs' `attested` and NVBSE designation labels. Whole words only
(a boundary is a non-letter or the text's edge), case-sensitive; at each position the longest form wins.
A one-word form starting lower-case (a common noun taken from a label) is not looked for as a name,
but for a canonical one (not `partial`) in the units where its entry is attested ("praetorium");
designations are looked for as written, only in their own unit.
Every occurrence in a verse is marked:

- settled (`entry`): a designation label of the entry for that unit, found once there (a designation
  found more than once is a `candidates` of its entry each time); or exactly one of the form's
  entries attested in the unit; or, outside the units where it is attested, a form of one entry
  only, or of several of which exactly one is attested in the unit's book, and in its chapter or in
  3 or more units of the book (Eden in Genesis, the garden), that entry attested (`attested`, not `mentioned`) elsewhere in the same book, the form not
  taken from a single word of a multiword name (forms.json's `partial`) and not a stoplist word,
  nor around a nested span settled to another entry attested in the unit (then candidates of both),
  nor in a unit that data/curated/unattested.json removed from the entry on review,
  nor in a unit that attests, unmatched, an entry (person or place: a people and its land count, Gesuri
  where Gessur is attested) one of whose forms has a word with the form's stem (first 4 letters, case, ligatures and doubled letters folded: the
  attested entry may be the one meant, spelled otherwise: those are candidates of both);
- under review (`candidates`, sorted): anything else, so a form shared by several entries (a person
  and a place included) with none or several attested, or a name whose only catalogued bearer
  belongs to another book (it may be an uncatalogued namesake): a `candidates` of one.

In an Old Testament unit (CBTUDR's data/books.json; deuterocanonical books included) a person candidate
must be attested somewhere in the Old Testament; a span left with none is not a mention. New Testament
units are not limited (they name Old Testament persons the sources cite only there), nor are places. A span inside another is kept; two crossing spans are both dropped and reported. Esther's
`@GREEK`/`@HEBREW` keys are attested as their unit without the suffix. Positions are UTF-16 code
units of text_plain; `check` is the first 8 hex digits of the SHA-256 of the span's UTF-8 text.
A private report (counts, unmatched attestations, crossing spans, review cases with their words)
goes to data-local/cbppedr/mentions/.

Usage: python extract_mentions.py   (no arguments; TEXTS and MENTIONS_LOCAL override the private folders)
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import sys
import unicodedata
from pathlib import Path
from typing import Callable

from audit_attested import TEXTS
from forms import FORMS, load_stoplist
